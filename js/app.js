const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];
const toast = (message) => {
  const element = $("#toast");
  element.textContent = message;
  element.classList.add("is-visible");
  window.setTimeout(() => element.classList.remove("is-visible"), 3200);
};

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;
  $$("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  $(".language-switcher__active").textContent = language === "en" ? "EN" : "සිං";
  localStorage.setItem("wedding-language", language);
}

function startCountdown() {
  const target = new Date("2026-12-10T09:00:00+05:30").getTime();
  const update = () => {
    const distance = Math.max(0, target - Date.now());
    const values = {
      days: Math.floor(distance / 86400000),
      hours: Math.floor(distance / 3600000) % 24,
      minutes: Math.floor(distance / 60000) % 60,
      seconds: Math.floor(distance / 1000) % 60
    };
    Object.entries(values).forEach(([key, value]) => { $(`#${key}`).textContent = String(value).padStart(2, "0"); });
  };
  update();
  window.setInterval(update, 1000);
}

function downloadCalendar() {
  const calendar = [
    "BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Nuwan and Tharushi//Wedding//EN", "BEGIN:VEVENT",
    "UID:nuwan-tharushi-20261210@wedding", "DTSTAMP:20260101T000000Z", "DTSTART;TZID=Asia/Colombo:20261210T090000",
    "DTEND;TZID=Asia/Colombo:20261210T130000", "SUMMARY:Nuwan & Tharushi — Wedding Celebration",
    "LOCATION:Sanctuary Lodge\\, Kaduwela", "DESCRIPTION:Join Nuwan and Tharushi as they begin their forever.",
    "END:VEVENT", "END:VCALENDAR"
  ].join("\r\n");
  const blob = new Blob([calendar], { type: "text/calendar;charset=utf-8" });
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = "nuwan-and-tharushi-wedding.ics";
  link.click();
  URL.revokeObjectURL(link.href);
  toast(document.documentElement.lang === "si" ? "දින දර්ශන ගොනුව බාගත වේ." : "Your calendar file is downloading.");
}

function initializeLightbox() {
  const lightbox = $("#lightbox");
  const image = $("#lightboxImage");
  const close = () => { lightbox.classList.remove("is-open"); lightbox.setAttribute("aria-hidden", "true"); };
  $$(".gallery-item").forEach((item) => item.addEventListener("click", () => {
    const source = item.querySelector("img");
    image.src = source.src;
    image.alt = source.alt;
    lightbox.classList.add("is-open");
    lightbox.setAttribute("aria-hidden", "false");
  }));
  $("#lightboxClose").addEventListener("click", close);
  lightbox.addEventListener("click", (event) => { if (event.target === lightbox) close(); });
  document.addEventListener("keydown", (event) => { if (event.key === "Escape") close(); });
}

function initializeApp() {
  document.body.classList.add("is-locked");
  const savedLanguage = localStorage.getItem("wedding-language");
  setLanguage(savedLanguage === "si" ? "si" : "en");
  startCountdown();
  initializeLightbox();
  const observer = new IntersectionObserver((entries) => entries.forEach((entry) => {
    if (entry.isIntersecting) { entry.target.classList.add("is-visible"); observer.unobserve(entry.target); }
  }), { threshold: .12 });
  $$(".reveal").forEach((element) => observer.observe(element));

  $("#openInvitation").addEventListener("click", () => {
    $("#preloader").classList.add("is-hidden");
    $("#siteShell").classList.add("is-visible");
    $("#siteShell").setAttribute("aria-hidden", "false");
    document.body.classList.remove("is-locked");
    const music = $("#backgroundMusic");
    music.play().catch(() => {});
  });
  $("#languageToggle").addEventListener("click", () => setLanguage(document.documentElement.lang === "en" ? "si" : "en"));
  $("#menuToggle").addEventListener("click", () => {
    const menu = $(".topbar__nav");
    const expanded = $("#menuToggle").getAttribute("aria-expanded") === "true";
    $("#menuToggle").setAttribute("aria-expanded", String(!expanded));
    menu.classList.toggle("is-open", !expanded);
  });
  $$(".topbar__nav a").forEach((link) => link.addEventListener("click", () => $(".topbar__nav").classList.remove("is-open")));
  $("#calendarButton").addEventListener("click", downloadCalendar);
  $("#shareButton").addEventListener("click", async () => {
    const shareData = { title: "Nuwan & Tharushi — Wedding Invitation", text: "Join us on 10 December 2026 at Sanctuary Lodge, Kaduwela.", url: window.location.href };
    if (navigator.share) await navigator.share(shareData).catch(() => {});
    else {
      await navigator.clipboard.writeText(window.location.href);
      toast(document.documentElement.lang === "si" ? "ආරාධනා සබැඳිය පිටපත් කරන ලදී." : "Invitation link copied.");
    }
  });
  $("#rsvpForm").addEventListener("submit", (event) => {
    event.preventDefault();
    const data = new FormData(event.currentTarget);
    const message = [
      "Hello Nuwan & Tharushi! I would like to RSVP for your wedding.",
      `Name: ${data.get("name")}`, `Attendance: ${data.get("attendance")}`, `Number of guests: ${data.get("guests")}`,
      data.get("message") ? `Message: ${data.get("message")}` : ""
    ].filter(Boolean).join("\n");
    window.open(`https://wa.me/94760481677?text=${encodeURIComponent(message)}`, "_blank", "noopener");
  });
}

window.addEventListener("DOMContentLoaded", initializeApp);
